// Ключ операции из выписки — защита от дублей при повторной загрузке.
// Нужен и разбору выписок (вкладка «Деньги»), и починке сохранённых данных (storage).

interface OperationId {
  account?: string // номер лицевого счёта ('' или нет — неизвестен)
  doc: string
  date: string // 'YYYY-MM-DD'
  time: string // 'HH:MM:SS'
}

// 'счёт|документ|дата время'. Номер счёта обязателен: перевод между своими счетами
// есть в ОБЕИХ выписках (карты и накопительного) с тем же документом и временем,
// но с разным знаком — без счёта одна выписка затирала бы другую.
// Если счёт неизвестен (старые данные, выписка без номера) — старый формат без счёта.
export function operationKey(op: OperationId): string {
  return op.account ? `${op.account}|${legacyOperationKey(op)}` : legacyOperationKey(op)
}

// Старый ключ (до номера счёта): 'документ|дата время'. Нужен, чтобы узнать
// операции и пополнения копилки, сохранённые старой версией.
export function legacyOperationKey(op: OperationId): string {
  return `${op.doc}|${op.date} ${op.time}`
}
